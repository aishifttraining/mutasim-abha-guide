function createFoodExplorer() {
  const explorer = document.getElementById("food-explorer");
  if (!explorer) return null;

  const trigger = explorer.querySelector("[data-food-explorer-trigger]");
  const panel = explorer.querySelector("#food-explorer-panel");
  const chooser = explorer.querySelector("[data-food-chooser]");
  const results = explorer.querySelector("[data-food-results]");
  const regionButtons = [...explorer.querySelectorAll("[data-food-region]")];
  const filterButtons = [...explorer.querySelectorAll("[data-food-filter]")];
  const changeRegionButtons = [...explorer.querySelectorAll("[data-food-change-region]")];
  const selectedRegionHeading = explorer.querySelector("[data-food-selected-region]");
  const placeGrid = explorer.querySelector("[data-food-place-grid]");
  const emptyState = explorer.querySelector("[data-food-empty]");
  const emptyCopy = explorer.querySelector("[data-food-empty-copy]");
  const status = explorer.querySelector("[data-food-status]");
  const surprise = explorer.querySelector("[data-food-surprise]");
  const surpriseButton = explorer.querySelector("[data-food-surprise-button]");
  const surpriseAgainButton = explorer.querySelector("[data-food-surprise-again]");
  const surpriseResult = explorer.querySelector("[data-food-surprise-result]");
  let selectedRegion = null;
  let selectedCategory = "all";
  let selectedSurprisePlaceId = null;
  const lastSurprisePlaceIds = new Map();

  function format(template, values) {
    return Object.entries(values).reduce(
      (text, [key, value]) => text.replaceAll(`{${key}}`, value),
      template
    );
  }

  function regionName(copy, region) {
    return copy[`foodRegion${region === "alnamas" ? "AlNamas" : region[0].toUpperCase() + region.slice(1)}`];
  }

  function categoryName(copy, category) {
    const names = {
      all: copy.foodFilterAll,
      cafe: copy.foodFilterCafes,
      restaurant: copy.foodFilterRestaurants
    };
    return names[category];
  }

  function placeIcon(type) {
    const icon = document.createElement("span");
    icon.className = `food-place-card__icon food-place-card__icon--${type}`;
    icon.setAttribute("aria-hidden", "true");
    return icon;
  }

  function createPlaceCard(place, copy) {
    const card = document.createElement("article");
    card.className = "food-place-card";

    const image = document.createElement("img");
    image.className = "food-place-card__image";
    image.src = place.image;
    image.alt = place.imageAlt[document.documentElement.lang];
    image.width = 1200;
    image.height = 675;
    image.loading = "lazy";
    image.decoding = "async";

    const heading = document.createElement("h4");
    heading.textContent = place.name[document.documentElement.lang];

    const type = document.createElement("p");
    type.className = "food-place-card__type";
    type.textContent = place.type === "cafe" ? copy.foodTypeCafe : copy.foodTypeRestaurant;

    const description = document.createElement("p");
    description.className = "food-place-card__description";
    description.textContent = place.description[document.documentElement.lang];

    const imageNote = document.createElement("p");
    imageNote.className = "food-place-card__image-note";
    imageNote.hidden = place.imageKind !== "category";
    imageNote.textContent = copy.foodCategoryImageNote;

    const mapLink = document.createElement("a");
    mapLink.className = "food-place-card__map";
    mapLink.href = place.mapUrl;
    mapLink.target = "_blank";
    mapLink.rel = "noopener noreferrer";
    mapLink.setAttribute("aria-label", format(copy.foodOpenMapsAria, { name: place.name[document.documentElement.lang] }));
    mapLink.append(document.createTextNode(copy.foodOpenMaps));
    const arrow = document.createElement("span");
    arrow.setAttribute("aria-hidden", "true");
    arrow.textContent = "↗";
    mapLink.append(arrow);

    card.append(image, placeIcon(place.type), type, heading, description, imageNote, mapLink);
    return card;
  }

  function surpriseScope() {
    return `${selectedRegion}:${selectedCategory}`;
  }

  function renderSurprise(copy, matchingPlaces) {
    const selectedPlace = matchingPlaces.find((place) => place.id === selectedSurprisePlaceId);
    if (!selectedPlace) selectedSurprisePlaceId = null;

    surprise.hidden = matchingPlaces.length === 0;
    surpriseResult.replaceChildren();
    surpriseResult.hidden = !selectedSurprisePlaceId;
    surpriseAgainButton.hidden = !selectedSurprisePlaceId;

    if (selectedPlace) {
      const badge = document.createElement("p");
      badge.className = "food-explorer__surprise-badge";
      badge.textContent = copy.foodSurpriseTitle;
      surpriseResult.append(badge, createPlaceCard(selectedPlace, copy));
    }
  }

  function chooseSurprise() {
    if (!selectedRegion) return;

    const copy = translations[document.documentElement.lang];
    const matchingPlaces = foodPlaces.filter((place) => (
      place.region === selectedRegion && (selectedCategory === "all" || place.type === selectedCategory)
    ));
    if (!matchingPlaces.length) {
      selectedSurprisePlaceId = null;
      renderSurprise(copy, matchingPlaces);
      status.textContent = copy.foodSurpriseEmpty;
      return;
    }

    const scope = surpriseScope();
    const previousId = lastSurprisePlaceIds.get(scope);
    const eligiblePlaces = matchingPlaces.length > 1
      ? matchingPlaces.filter((place) => place.id !== previousId)
      : matchingPlaces;
    const place = eligiblePlaces[Math.floor(Math.random() * eligiblePlaces.length)];
    selectedSurprisePlaceId = place.id;
    lastSurprisePlaceIds.set(scope, place.id);
    renderSurprise(copy, matchingPlaces);
    status.textContent = format(copy.foodSurpriseStatus, {
      region: regionName(copy, selectedRegion),
      name: place.name[document.documentElement.lang]
    });
  }

  function render() {
    const copy = translations[document.documentElement.lang];
    const hasSelection = Boolean(selectedRegion);
    chooser.hidden = hasSelection;
    results.hidden = !hasSelection;

    if (!hasSelection) {
      selectedSurprisePlaceId = null;
      surprise.hidden = true;
      surpriseResult.replaceChildren();
      surpriseResult.hidden = true;
      surpriseAgainButton.hidden = true;
      status.textContent = "";
      return;
    }

    const region = regionName(copy, selectedRegion);
    const matchingPlaces = foodPlaces.filter((place) => (
      place.region === selectedRegion && (selectedCategory === "all" || place.type === selectedCategory)
    ));
    selectedRegionHeading.textContent = region;
    placeGrid.replaceChildren();
    filterButtons.forEach((button) => {
      button.setAttribute("aria-pressed", String(button.dataset.foodFilter === selectedCategory));
    });
    renderSurprise(copy, matchingPlaces);

    const hasRegionPlaces = foodPlaces.some((place) => place.region === selectedRegion);
    emptyState.hidden = matchingPlaces.length > 0;
    if (matchingPlaces.length > 0) {
      matchingPlaces.forEach((place) => placeGrid.append(createPlaceCard(place, copy)));
      emptyCopy.textContent = "";
    } else {
      emptyCopy.textContent = hasRegionPlaces ? copy.foodNoMatches : copy.foodComingSoon;
    }

    status.textContent = format(copy.foodStatus, {
      count: String(matchingPlaces.length),
      region,
      filter: categoryName(copy, selectedCategory)
    });
  }

  function openChooser() {
    panel.hidden = false;
    trigger.setAttribute("aria-expanded", "true");
    if (!selectedRegion) chooser.hidden = false;
  }

  function closeChooser({ restoreFocus = false } = {}) {
    panel.hidden = true;
    trigger.setAttribute("aria-expanded", "false");
    if (restoreFocus) trigger.focus();
  }

  trigger.addEventListener("click", () => {
    if (panel.hidden) openChooser();
    else closeChooser();
  });

  regionButtons.forEach((button) => button.addEventListener("click", () => {
    selectedRegion = button.dataset.foodRegion;
    selectedCategory = "all";
    render();
    explorer.querySelector("[data-food-filter=\"all\"]").focus();
  }));

  filterButtons.forEach((button) => button.addEventListener("click", () => {
    selectedCategory = button.dataset.foodFilter;
    render();
  }));

  surpriseButton.addEventListener("click", chooseSurprise);
  surpriseAgainButton.addEventListener("click", chooseSurprise);

  changeRegionButtons.forEach((button) => button.addEventListener("click", () => {
    selectedRegion = null;
    selectedCategory = "all";
    render();
    regionButtons[0].focus();
  }));

  document.addEventListener("keydown", (event) => {
    if (event.key === "Escape" && !panel.hidden) closeChooser({ restoreFocus: true });
  });

  return { refresh: render };
}

