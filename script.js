function getStoredLanguage() {
  try {
    const storedLanguage = localStorage.getItem(storageKey);
    return storedLanguage === "ar" || storedLanguage === "en" ? storedLanguage : "ar";
  } catch {
    return "ar";
  }
}

function setStoredLanguage(language) {
  try {
    localStorage.setItem(storageKey, language);
  } catch {
    // The page stays usable when browser storage is unavailable.
  }
}

function getStoredTheme() {
  try {
    const storedTheme = localStorage.getItem(themeStorageKey);
    return storedTheme === "light" || storedTheme === "dark" ? storedTheme : "light";
  } catch {
    return "light";
  }
}

function setStoredTheme(theme) {
  try {
    localStorage.setItem(themeStorageKey, theme);
  } catch {
    // The page stays usable when browser storage is unavailable.
  }
}

function setTheme(theme, announce = false) {
  if (theme !== "light" && theme !== "dark") return;

  const root = document.documentElement;
  const language = root.lang === "en" ? "en" : "ar";
  const copy = translations[language];
  const nextTheme = theme === "dark" ? "light" : "dark";

  root.dataset.theme = theme;
  root.style.colorScheme = theme;
  themeButton.setAttribute("aria-pressed", String(theme === "dark"));
  themeButton.dataset.theme = theme;
  themeButton.setAttribute("aria-label", copy[`themeSwitch${nextTheme === "dark" ? "Dark" : "Light"}`]);
  themeButton.setAttribute("title", copy[`themeSwitch${nextTheme === "dark" ? "Dark" : "Light"}`]);
  themeButton.querySelector(".sr-only").textContent = copy[`themeSwitch${nextTheme === "dark" ? "Dark" : "Light"}`];
  setStoredTheme(theme);

  if (announce) themeStatus.textContent = copy[`themeChanged${theme === "dark" ? "Dark" : "Light"}`];
}

function setLanguage(language, announce = false) {
  const copy = translations[language];
  if (!copy) return;

  const root = document.documentElement;
  root.lang = language;
  root.dir = language === "ar" ? "rtl" : "ltr";
  document.title = copy.pageTitle;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (copy[key]) element.textContent = copy[key];
  });

  document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    const key = element.dataset.i18nAriaLabel;
    if (copy[key]) element.setAttribute("aria-label", copy[key]);
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    const key = element.dataset.i18nAlt;
    if (copy[key]) element.alt = copy[key];
  });

  languageButton.setAttribute("aria-pressed", String(language === "en"));
  languageButton.setAttribute("title", language === "ar" ? copy.languageSwitchAr : copy.languageSwitchEn);
  languageButton.dataset.currentLanguage = language;
  languageButton.querySelectorAll("[data-language-token]").forEach((token) => {
    token.dataset.active = String(token.dataset.languageToken === language);
  });
  setTheme(root.dataset.theme || getStoredTheme());
  setStoredLanguage(language);
  if (destinationSlider) destinationSlider.refresh();
  if (heroSlider) heroSlider.refresh();
  if (staysExplorer) staysExplorer.refresh();
  if (foodExplorer) foodExplorer.refresh();
  if (activitiesExplorer) activitiesExplorer.refresh();

  if (announce) languageStatus.textContent = copy[`languageChanged${language === "ar" ? "Ar" : "En"}`];
}

